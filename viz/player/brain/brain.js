// ------------------------------------------------------------- text layout
// Canvas has no wrapping: measure-and-wrap, then balance so multi-line blocks
// come out with near-equal line lengths instead of a long line + an orphan.
function wrapLines(text, maxWidth) {
  const words = text.split(" ");
  const lines = [];
  let cur = "";
  for (const w of words) {
    const trial = cur ? cur + " " + w : w;
    if (cur && ctx.measureText(trial).width > maxWidth) { lines.push(cur); cur = w; }
    else cur = trial;
  }
  if (cur) lines.push(cur);
  return lines;
}
function balancedLines(text, maxWidth) {
  const greedy = wrapLines(text, maxWidth);
  if (greedy.length < 2) return greedy;
  const n = greedy.length;
  let lo = ctx.measureText(text).width / n, hi = maxWidth;
  for (let i = 0; i < 8; i++) {
    const mid = (lo + hi) / 2;
    if (wrapLines(text, mid).length > n) lo = mid; else hi = mid;
  }
  return wrapLines(text, hi);
}
// Vertically-centered multi-line block at (W/2, yc).
function fillBlock(lines, yc, lineH) {
  const y0 = yc - ((lines.length - 1) * lineH) / 2;
  lines.forEach((l, i) => ctx.fillText(l, W / 2, y0 + i * lineH));
}

