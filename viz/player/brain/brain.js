// ---------------------------------------------------------------- layout
// One "mind" = a constellation: senses arc -> process cloud -> MEMORY spine
// (the hero) -> actions/guesses. Positions are in a local 0..1 box, mirrored
// for the FAKE side so the two minds face each other like a Rorschach.

function buildMind(seed) {
  const R = mulberry32(seed);
  const nodes = [];   // {x,y,r,kind,label,phase,freqK}
  const edges = [];   // {a,b,w,comet:{P,phi}|null}
  const add = (x, y, r, kind, label) => {
    nodes.push({
      x, y, r, kind, label,
      phase: R() * TAU,
      freqK: 2 + Math.floor(R() * 3), // 2..4 integer cycles per loop
    });
    return nodes.length - 1;
  };

  // Senses: the 10 real sensor groups, gentle arc on the far side.
  const senses = [];
  for (let i = 0; i < SENSE_LABELS.length; i++) {
    const p = i / (SENSE_LABELS.length - 1);
    const y = lerp(0.14, 0.86, p);
    const x = 0.055 + 0.05 * Math.sin(p * Math.PI) + (R() - 0.5) * 0.02;
    senses.push(add(x, y, 6.5, "sense", SENSE_LABELS[i]));
  }
  // Process: sampled encoder rows (embed = 64), loose two-column cloud.
  const process = [];
  for (let i = 0; i < ENC_LABELS.length; i++) {
    const col = i % 2;
    const p = Math.floor(i / 2) / 2;
    const x = 0.27 + col * 0.09 + (R() - 0.5) * 0.04;
    const y = lerp(0.22, 0.78, p) + (R() - 0.5) * 0.05;
    process.push(add(x, y, 5.5, "process", ENC_LABELS[i]));
  }
  // MEMORY spine: 12 real GRU units of the representative brain (of
  // DATA.hidden total), true indices as labels, sized by measured activity.
  const memory = [];
  for (let i = 0; i < DATA.display_units.length; i++) {
    const p = i / (DATA.display_units.length - 1);
    const y = lerp(0.10, 0.90, p);
    const x = 0.565 + 0.028 * Math.sin(p * Math.PI * 1.35 + 0.4);
    const r = 8.5 + 4 * DATA.unit_activity[i];
    memory.push(add(x, y, r, "memory", "unit " + DATA.display_units[i]));
    nodes[nodes.length - 1].unit = DATA.display_units[i];
    nodes[nodes.length - 1].signal = DATA.unit_signal[i];
  }
  // Actions: the 5 real motor heads; guesses: the 3 real readout heads.
  const actions = [];
  for (let i = 0; i < ACTION_LABELS.length; i++) {
    const p = i / (ACTION_LABELS.length - 1);
    actions.push(add(0.82 + (R() - 0.5) * 0.02, lerp(0.22, 0.78, p), 6.5, "action", ACTION_LABELS[i]));
  }
  const guesses = [];
  for (let i = 0; i < GUESS_LABELS.length; i++) {
    guesses.push(add(0.945, lerp(0.3, 0.7, i / 2), 6, "guess", GUESS_LABELS[i]));
  }

  // Clue cells: the units with the highest MEASURED world-signal
  // (DATA.ring_units). Ring strength = normalized measured signal; the bloom
  // still cascades top -> bottom along the spine.
  const clue = memory.filter((idx) => DATA.ring_units.includes(nodes[idx].unit));
  nodes.forEach((n, i) => { n.clue = clue.includes(i); });
  clue.forEach((idx, k) => { nodes[idx].clueOrder = k; });
  // The flaw: the sloppy velocity law enters through the motion senses.
  const glitch = senses[GLITCH_SENSE];
  nodes[glitch].glitch = true;

  // Edges. Comets ride a subset; periods divide T for seamless looping.
  const P_CHOICES = [2000, 3000, 4000, 6000];
  const connect = (from, to, fanMin, fanMax, cometProb) => {
    for (const a of from) {
      const fan = fanMin + Math.floor(R() * (fanMax - fanMin + 1));
      for (let k = 0; k < fan; k++) {
        const b = to[Math.floor(R() * to.length)];
        const w = 0.35 + R() * 0.65;
        const comet = R() < cometProb
          ? { P: P_CHOICES[Math.floor(R() * P_CHOICES.length)], phi: R() }
          : null;
        edges.push({ a, b, w, comet });
      }
    }
  };
  connect(senses, process, 2, 3, 0.5);
  connect(process, memory, 2, 3, 0.55);
  connect(memory, actions, 1, 2, 0.45);
  connect(memory.filter((_, i) => i % 3 === 0), guesses, 1, 1, 0.6);

  return { nodes, edges, memory, clue };
}

