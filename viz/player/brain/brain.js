// ---------------------------------------------------------------- frame
function render(t) {
  t = ((t % T) + T) % T;
  ctx.save();
  // Gentle breathing camera (one full cycle per loop => seamless).
  const s = 1 + 0.012 * Math.sin(TAU * (t / T));
  ctx.translate(W / 2, H / 2); ctx.scale(s, s); ctx.translate(-W / 2, -H / 2);
  drawBackground(t);
  for (const p of PANELS) drawMind(p, t);
  drawDivider(t);
  ctx.restore();
  drawVignette();
  drawCaptionBand();
  drawNarration(t);
  drawCaption();
}

