/* ItaSoRL "Two Minds" brain film: deterministic canvas renderer.
 *
 * A stylized (illustrative, not data-literal) recreation of the brain-pair
 * story: one trained brain, frozen, run in a REAL and a FAKE world, with teal
 * rings blooming on the memory cells whose readings differ most between them.
 *
 * Design contract (matches viz/player capture pipeline):
 *   window.__ready    true once fonts are loaded and first frame drew
 *   window.__size     [w, h] canvas pixel box
 *   window.__duration total ms
 *   window.__seek(t)  render the exact frame at time t (pure function of t)
 *   window.__sceneSource = "stylized"  (this film is illustrative art)
 *
 * Numbers are REAL and come from the corrected trainer (docs/CORRECTIONS.md,
 * docs/FINDINGS.md section 17): run C1, ten seeds per arm, drift 0.45, read out
 * and never rewarded. They live in FILM below, one line each with its artifact;
 * scripts/dump_brain_film_data.py refuses to write brain data while any display
 * there disagrees with the committed artifacts, and tests/test_brain_film.py
 * runs the same check in CI.
 * Each figure is a mean over ten brains of one kind, so the rows and tiles say
 * "untrained brains" and "brains like this one"; the brain drawn on screen is
 * one of the ten (its own pooled target is in brain-data.js).
 *   untrained brains       0.523  52%. Interval [0.491, 0.554] includes 0.5,
 *                                 so the film may call it a coin flip.
 *   brains like this one   0.733  73%. Survival plus next-observation
 *                                 prediction, 300 updates, 8 of 10 seeds at
 *                                 the bar, interval [0.669, 0.797].
 *   the bar                0.65   Registered before the run.
 *   predict-only brains    0.721  72%. A trunk trained only to predict, fed this
 *                                 brain's own observation streams (17.6). It
 *                                 sits within about 0.01 of 0.733, so the
 *                                 reading that credited the survival objective
 *                                 is withdrawn.
 *   no prediction job      0.613  61% at 300 updates, under the bar (17.4), and
 *                          0.685  69% at 450 (17.10). The auxiliary result is
 *                                 bounded by budget, so the card names both.
 *   two identical worlds   0.559  56%, the L0 gate on two authentic world
 *                                 samples. It is not equivalent to 0.5, so the
 *                                 registered rule is NOT met (17.2); the
 *                                 decodability clauses are.
 * What the picture may not say, and does not: that survival pressure causes the
 * signal; that it is independent of behavior (the best-fitting behavior and
 * sensory control leaves 0.620, under the bar, 17.8); that memory stores it
 * (under identical input the difference fades within a few steps, so the frozen
 * verdict is "retention not shown", 17.7). The ring cycle rises after the event
 * and releases before the loop ends, which is as far as the picture goes.
 *
 * Historical numbers, kept here so the old cut can be read: the September render
 * showed one meter climbing from 49% (0.488, the pre-correction untrained floor)
 * to 73% (0.726, the pre-correction section 10.4 behavior-control residual) as if
 * one brain changed, and its brain data came from the pre-correction held-out
 * pools (seed 8, pooled 0.752). None of those figures is on screen any more.
 *
 * The layout and motion stay stylized; names and numbers do not. Sense, action
 * and readout names mirror the real obs and head spec (viz_mind_learning.py
 * SENSOR_GROUPS / MOTOR_HEADS), the memory spine shows 12 of the 96 recurrent
 * units of one representative trained brain, and the teal rings sit on the
 * units with the highest MEASURED world-signal (brain-data.js, generated by
 * scripts/dump_brain_film_data.py from state pools rebuilt out of the corrected
 * agents by scripts/regenerate_state_dumps.py).
 *
 * Seamless loop: every animated quantity is periodic in T = duration.
 * Comet periods divide T; breathing/drift use integer cycles per loop; the
 * signal sweep, ring envelopes and readout bars are functions of (t mod T).
 * Frame(0) therefore equals Frame(T) exactly, with no crossfade seam.
 */

