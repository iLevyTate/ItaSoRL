function bezier(ax, ay, bx, by, s) {
  // Quadratic with a control point pushed perpendicular for a gentle arc.
  const mx = (ax + bx) / 2, my = (ay + by) / 2;
  const dx = bx - ax, dy = by - ay;
  const L = Math.hypot(dx, dy) || 1;
  const cx = mx - dy / L * L * 0.14, cy = my + dx / L * L * 0.14;
  const q = 1 - s;
  return [
    q * q * ax + 2 * q * s * cx + s * s * bx,
    q * q * ay + 2 * q * s * cy + s * s * by,
    cx, cy,
  ];
}

function drawBackground(t) {
  const u = frac(t / T);
  ctx.fillStyle = BG0;
  ctx.fillRect(0, 0, W, H);
  // Slow nebula blobs on closed Lissajous paths (integer cycles => seamless).
  const blobs = [
    { cx: 0.24, cy: 0.30, r: 0.55, c: [34, 28, 66], k1: 1, k2: 2, amp: 0.045, phi: 0.0 },
    { cx: 0.78, cy: 0.34, r: 0.50, c: [46, 26, 62], k1: 1, k2: 1, amp: 0.05, phi: 2.1 },
    { cx: 0.52, cy: 0.78, r: 0.62, c: [24, 30, 58], k1: 2, k2: 1, amp: 0.04, phi: 4.0 },
  ];
  for (const b of blobs) {
    const x = (b.cx + b.amp * Math.cos(TAU * b.k1 * u + b.phi)) * W;
    const y = (b.cy + b.amp * Math.sin(TAU * b.k2 * u + b.phi)) * H;
    const r = b.r * Math.max(W, H);
    const g = ctx.createRadialGradient(x, y, 0, x, y, r);
    g.addColorStop(0, rgba(b.c, 0.55));
    g.addColorStop(1, rgba(b.c, 0));
    ctx.fillStyle = g;
    ctx.fillRect(0, 0, W, H);
  }
}

