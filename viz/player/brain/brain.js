function rawXY(panel, n) {
  const lx = panel.mirror ? 1 - n.x : n.x;
  return [panel.x + lx * panel.w, panel.y + n.y * panel.h];
}

function panelFocusCenter(panel) {
  // Centroid of the focused group in this panel's raw (unzoomed) space.
  if (panel._fc) return panel._fc;
  let sx = 0, sy = 0, k = 0;
  for (const nd of MIND.nodes) {
    if (!SECTION.focus.includes(nd.kind)) continue;
    const [x, y] = rawXY(panel, nd);
    sx += x; sy += y; k++;
  }
  panel._fc = [sx / Math.max(1, k), sy / Math.max(1, k)];
  return panel._fc;
}

function nodeXY(panel, n) {
  const [x, y] = rawXY(panel, n);
  if (FOCUS_Z === 1) return [x, y];
  // Camera: move the focused centroid to the panel center and magnify about
  // it, so the section's subject fills the frame and the rest exits stage.
  const [fx, fy] = panelFocusCenter(panel);
  const cx = panel.x + panel.w / 2;
  const cy = panel.y + panel.h / 2;
  return [cx + (x - fx) * FOCUS_Z, cy + (y - fy) * FOCUS_Z];
}

// ---------------------------------------------------------------- timing
// One "training sweep" per loop crosses each panel; as it passes the memory
// spine the clue rings bloom, hold with a glow-pulse, then decay before the
// next pass. All envelopes are functions of u = (t mod T)/T.

const SWEEP_IN = 0.10, SWEEP_OUT = 0.46;   // sweep front active window (u)
const BLOOM_AT = 0.30;                      // u when front hits the spine
const BLOOM_STAGGER = 0.022;                // per-cell delay (u units)
const RING_HOLD_END = 0.86;                 // u when rings start to release
const RING_DECAY = 0.10;                    // release length (u units)

function sweepX(panel, u) {
  // Front sweeps across the panel from the senses side toward actions.
  const s = smooth((u - SWEEP_IN) / (SWEEP_OUT - SWEEP_IN));
  const x0 = panel.mirror ? panel.x + panel.w * 1.08 : panel.x - panel.w * 0.08;
  const x1 = panel.mirror ? panel.x - panel.w * 0.08 : panel.x + panel.w * 1.08;
  return lerp(x0, x1, s);
}
function sweepAlpha(u) {
  const a = smooth((u - SWEEP_IN) / 0.05) * (1 - smooth((u - SWEEP_OUT + 0.05) / 0.05));
  return 0.85 * a;
}

function ringEnv(u, order) {
  const start = BLOOM_AT + order * BLOOM_STAGGER;
  const uu = frac(u - start + 1);           // time since this cell's bloom, in u
  const attack = smooth(uu / 0.03);          // ~0.36s bloom-in
  const releaseAt = frac(RING_HOLD_END - start + 1);
  const rel = 1 - smooth((uu - releaseAt) / RING_DECAY);
  return clamp01(attack * rel);
}

